SET LIST ON;
SELECT rf.RDB$RELATION_NAME, rf.RDB$FIELD_NAME, f.RDB$FIELD_TYPE,
       f.RDB$FIELD_LENGTH, f.RDB$FIELD_SCALE, rf.RDB$NULL_FLAG
FROM RDB$RELATION_FIELDS rf
JOIN RDB$FIELDS f ON f.RDB$FIELD_NAME = rf.RDB$FIELD_SOURCE
WHERE rf.RDB$RELATION_NAME IN ('USUARIOS', 'ACESSOSUSUARIO')
ORDER BY rf.RDB$RELATION_NAME, rf.RDB$FIELD_POSITION;
SELECT rc.RDB$RELATION_NAME, rc.RDB$CONSTRAINT_NAME, rc.RDB$CONSTRAINT_TYPE,
       iseg.RDB$FIELD_NAME
FROM RDB$RELATION_CONSTRAINTS rc
LEFT JOIN RDB$INDEX_SEGMENTS iseg ON iseg.RDB$INDEX_NAME = rc.RDB$INDEX_NAME
WHERE rc.RDB$RELATION_NAME IN ('USUARIOS', 'ACESSOSUSUARIO');
SELECT rdb$trigger_name, rdb$trigger_type, rdb$trigger_sequence, rdb$trigger_inactive
FROM rdb$triggers
WHERE rdb$relation_name IN ('USUARIOS', 'ACESSOSUSUARIO');
QUIT;
